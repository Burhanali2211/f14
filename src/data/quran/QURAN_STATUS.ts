export type SurahStatus = 'complete' | 'incomplete' | 'missing';

export interface SurahProgress {
  number: number;
  name: string;
  arabicName: string;
  totalVerses: number;
  addedVerses?: number;
  status: SurahStatus;
  remaining?: number;
}

export function getSurahStatus(surahNumber: number): SurahProgress | undefined {
  const completed = QURAN_STATUS.completed.find(s => s.number === surahNumber);
  if (completed) return completed as SurahProgress;
  
  const incomplete = QURAN_STATUS.incomplete.find(s => s.number === surahNumber);
  if (incomplete) return incomplete as SurahProgress;
  
  const missing = QURAN_STATUS.missing.find(s => s.number === surahNumber);
  if (missing) return { ...missing, addedVerses: 0 } as SurahProgress;
  
  return undefined;
}

export function getAvailableSurahs(): number[] {
  return [
    ...QURAN_STATUS.completed.map(s => s.number),
    ...QURAN_STATUS.incomplete.map(s => s.number),
  ].sort((a, b) => a - b);
}
