// Shia note: Surah Al-Ahzab contains some of the most critically important
// verses in Shia theology:
//
// Verse 33 — AYAH OF TATHIR (Verse of Purification):
// "Allah only wishes to remove impurity from you, O People of the House,
// and to purify you with a thorough purification."
// Shia scholars (including Allama Tabataba'i in Al-Mizan) establish based on
// chains of narration that this verse was revealed specifically about:
// the Prophet (s), Imam Ali (a.s.), Fatima al-Zahra (a.s.),
// Imam Hasan (a.s.), and Imam Husayn (a.s.) — the Ahl al-Kisa.
// The pronoun shifts from feminine (addressing the Prophet's wives) to
// masculine (عنكم — 'ankum) proving a different group is addressed.
// The hadith al-kisa (Narration of the Cloak) establishes the identity
// of the Ahlulbayt definitively.
//
// Verse 56 — "Indeed Allah and His angels bless the Prophet. O you who
// have faith! Invoke blessings on him and invoke Peace upon him in a
// worthy manner." — The complete salawat in Shia tradition includes
// the Ahlulbayt: "Allahumma salli ala Muhammad wa ali Muhammad."
//
// Verse 6 — "The Prophet is closer to the faithful than their own souls."
// — interpreted in Shia theology as establishing the Prophet's authority
// (wilayah) over believers, which extends to the Imams by designation.

